#!/usr/bin/env python3
"""Generate payloads.h from the release artifacts in payloads/."""
import pathlib

PAYLOADS = [
    ("payload_linux", "voica-linux-x64"),
    ("payload_win32", "voica-win32-x64.exe"),
    ("payload_darwin", "voica-darwin-universal"),
    ("payload_recorder_wasm", "recorder.wasm"),
]

root = pathlib.Path(__file__).parent
out = ["/* generated by gen_payloads.py — do not edit */"]
for name, fname in PAYLOADS:
    data = (root / "payloads" / fname).read_bytes()
    out.append(f"static const unsigned char {name}[] = {{")
    for i in range(0, len(data), 16):
        out.append(",".join(str(b) for b in data[i:i + 16]) + ",")
    out.append("};")
    out.append(f"static const unsigned int {name}_len = {len(data)};")
(root / "payloads.h").write_text("\n".join(out) + "\n")
print("payloads.h written")
